export function translate(language: Language, text: string): string {
  return language === 'et' ? estonian[text] ?? text : text;
}
export function loadLanguage(): Language {
  try { const saved = localStorage.getItem(LANGUAGE_KEY); if (saved === 'en' || saved === 'et') return saved; } catch { /* Language switching works without storage. */ }
  return 'en';
}
export function saveLanguage(language: Language): void {
  try { localStorage.setItem(LANGUAGE_KEY, language); } catch { /* Keep the preference for this session. */ }
}
